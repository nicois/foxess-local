#!/usr/bin/env bash
# Generates the standalone installer.sh (run it via `make installer`, or
# directly: bash deploy/gen-installer.sh > installer.sh).
#
# The deploy/ files and config.example.toml are the sources of truth;
# this script only inlines them into a single self-contained script so
# the gateway never needs a repo checkout — the installer + the binary
# for the gateway's architecture are the entire installation surface.
set -euo pipefail

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

# emit <relpath> <dest> <mode> <owner:group or ->
# prints a write_file call with the file's content as a heredoc. The
# delimiter is QUOTED: unquoted, the embedded scripts' $1/backticks
# would expand (and execute) at install time.
emit() {
	local name
	name="$(echo "$1" | tr '/.' '__')"
	printf "write_file %s %s %s <<'__FOXESS_%s__'\n" "$2" "$3" "$4" "$name"
	cat "$REPO_DIR/$1"
	printf '__FOXESS_%s__\n' "$name"
}

# Preflight: every embedded source must exist before a single byte of
# installer.sh is written — a mid-stream generator failure would leave
# a truncated (and possibly still executable) installer behind.
for src in deploy/apply-gate.sh deploy/check-gate.sh deploy/inventory-gate.sh \
	deploy/rollback.sh deploy/upgrade-guard.sh deploy/gate.nft deploy/foxess-gate.service deploy/foxess-gate-early.service \
	deploy/foxess-gate-check.service deploy/foxess-gate-check.timer \
	deploy/foxess-local.service config.example.toml; do
	[ -f "$REPO_DIR/$src" ] || {
		echo "gen-installer: missing source: $src" >&2
		exit 1
	}
done

cat <<'PREAMBLE'
#!/usr/bin/env bash
# foxess-local installer (standalone) — GENERATED by `make installer`
# (deploy/gen-installer.sh). Do not edit: edit deploy/ and regenerate.
#
# Usage (as root, on the host that is the inverter's network gateway):
#   installer.sh install --inverter-ip IP [--inverter-mac MAC] [--binary FILE]
#                        [--no-inverter]
#                        [--forward-mode off|telemetry_only|full] [--no-start]
#                        [--gate-only | --app-only] [--fix] [--allow-downgrade]
#   installer.sh check                  # requirements only, changes nothing
#   installer.sh uninstall [--purge]    # --purge also removes config + data
#   installer.sh FILE                   # legacy form: install with this binary
#
# install:
#   - the binary: --binary, else foxess-local_linux_<arch> next to this
#     script, else ./foxess-local
#   - --inverter-ip is required on the first install (it is kept in
#     /etc/foxess-local/gate.env afterwards), unless --no-inverter: then
#     the gate is installed but stays off, until a later
#     install --inverter-ip IP sets the address (an OpenStick appliance's
#     wizard does that)
#   - idempotent; /etc/foxess-local/config.toml and gate.env are KEPT
#   - mints the first installer token (printed once) when none exists
#   - the first install asks what the vendor cloud may receive
#     (--forward-mode answers it; without a terminal it is off)
#   - starts the gate and the app and checks the result (--no-start
#     installs only; --enable is accepted for older scripts)
#   - --gate-only: the egress gate alone (the app runs in a container)
#   - --app-only: the app alone (the gate is managed elsewhere)
#   - missing gate tools and IPv4 forwarding: offered as fixes, one
#     yes/no question each (--fix answers yes; without a terminal and
#     without --fix nothing is changed and the fixes are printed)
#
# Layout:
#   /usr/local/lib/foxess-local/   gate scripts + upgrade-guard.sh (root)
#   /etc/foxess-local/             gate.nft, gate.env (root 0644),
#                                  config.toml (foxess 0600)
#   /etc/systemd/system/foxess-*.{service,timer}
#   /var/lib/foxess-gate/          gate state (root)
#   /var/lib/foxess-local/         app data (foxess 0700) and
#                                  bin/foxess-local (foxess-owned: the
#                                  app updates itself, no root)
set -euo pipefail
trap 'rm -f /etc/foxess-local/*.tmp."$$" /etc/systemd/system/*.tmp."$$" \
	/usr/local/lib/foxess-local/*.tmp."$$" /var/lib/foxess-local/bin/*.tmp."$$"' EXIT

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
die() { echo "installer: $*" >&2; exit 1; }
say() { echo "installer: $*"; }

# ---- arguments ----
CMD=install
case "${1:-}" in
install | check | uninstall) CMD="$1"; shift ;;
esac
INVERTER_IP="" INVERTER_MAC="" BIN="" ENABLE=1 PURGE="" GATE=1 APP=1 FORWARD_MODE="" FIX="" DOWNGRADE="" NO_INVERTER=""
while [ $# -gt 0 ]; do
	case "$1" in
	--inverter-ip) INVERTER_IP="${2:-}"; shift 2 ;;
	--inverter-ip=*) INVERTER_IP="${1#*=}"; shift ;;
	--inverter-mac) INVERTER_MAC="${2:-}"; shift 2 ;;
	--inverter-mac=*) INVERTER_MAC="${1#*=}"; shift ;;
	--binary) BIN="${2:-}"; shift 2 ;;
	--binary=*) BIN="${1#*=}"; shift ;;
	--enable) ENABLE=1; shift ;; # the default now; kept for older scripts
	--no-start) ENABLE=""; shift ;;
	--forward-mode) FORWARD_MODE="${2:-}"; shift 2 ;;
	--forward-mode=*) FORWARD_MODE="${1#*=}"; shift ;;
	--purge) PURGE=1; shift ;;
	--fix) FIX=1; shift ;;
	--allow-downgrade) DOWNGRADE=1; shift ;;
	--gate-only) APP=""; shift ;;
	--app-only) GATE=""; shift ;;
	--no-inverter) NO_INVERTER=1; shift ;;
	-h | --help) sed -n '2,30p' "$0"; exit 0 ;;
	-*) die "unknown option $1 (see --help)" ;;
	*) BIN="$1"; shift ;; # legacy: installer.sh FILE
	esac
done

# ---- requirements ----
ARCH=""
case "$(uname -m)" in
x86_64) ARCH=amd64 ;;
aarch64 | arm64) ARCH=arm64 ;;
armv7l | armv7*) ARCH=armv7 ;;
esac

check_requirements() {
	local bad=""
	[ "$(id -u)" = 0 ] || { echo "  - run as root"; bad=1; }
	[ "$(uname -s)" = Linux ] || { echo "  - Linux only"; bad=1; }
	[ -n "$ARCH" ] || { echo "  - unsupported CPU $(uname -m) (amd64, arm64, armv7)"; bad=1; }
	command -v systemctl >/dev/null || { echo "  - systemd is required"; bad=1; }
	if [ -n "$GATE" ]; then
		command -v nft >/dev/null || { echo "  - nftables (the nft command) is required for the gate"; bad=1; }
		command -v ip >/dev/null || { echo "  - iproute2 (the ip command) is required for the gate"; bad=1; }
		command -v conntrack >/dev/null || echo "  - optional, not installed: conntrack (the gate check's connection scan is skipped)"
		if ! modprobe -n -q nft_tproxy 2>/dev/null && ! grep -q nft_tproxy /proc/modules 2>/dev/null; then
			echo "  ! the nft_tproxy kernel module was not found; the gate needs TPROXY support"
		fi
		if [ "$(cat /proc/sys/net/ipv4/ip_forward 2>/dev/null)" != 1 ]; then
			echo "  ! IPv4 forwarding is off: the inverter's NTP (the only other traffic the gate allows) will not pass"
			echo "    fix: echo net.ipv4.ip_forward=1 > /etc/sysctl.d/90-foxess.conf && sysctl --system"
		fi
		if command -v docker >/dev/null 2>&1 && nft list chain ip filter FORWARD 2>/dev/null | grep -q 'policy drop'; then
			echo "  ! Docker sets the forward policy to drop: the inverter's NTP will not pass"
			echo "    fix: iptables -I DOCKER-USER -s <inverter-ip> -p udp --dport 123 -j ACCEPT"
		fi
		if systemctl is-enabled -q nftables.service 2>/dev/null; then
			echo "  ! nftables.service is enabled: restarting it (or a reboot) may flush the gate until the"
			echo "    5-minute check restores it; the boot-time drop keeps the inverter blocked meanwhile"
		fi
	fi
	if [ -n "$APP" ]; then
		if command -v ufw >/dev/null 2>&1 && ufw status 2>/dev/null | grep -q '^Status: active'; then
			echo "  ! ufw is active: the web UI (port 18080) may be blocked"
			echo "    fix: ufw allow from 192.168.0.0/16 to any port 18080 proto tcp   (your LAN range)"
		fi
		if command -v firewall-cmd >/dev/null 2>&1 && firewall-cmd --state >/dev/null 2>&1; then
			echo "  ! firewalld is running: the web UI (port 18080) may be blocked"
			echo "    fix: firewall-cmd --permanent --add-port=18080/tcp && firewall-cmd --reload"
		fi
	fi
	[ -z "$bad" ]
}

# pkg_manager: this system's package manager (apt, dnf, zypper, pacman,
# apk), or nothing.
pkg_manager() {
	local pm
	for pm in apt-get dnf zypper pacman apk; do
		if command -v "$pm" >/dev/null 2>&1; then echo "${pm%-get}"; return; fi
	done
}

# pkg_for PM TOOL: the package that provides a gate tool.
pkg_for() {
	case "$2" in
	nft) echo nftables ;;
	ip) case "$1" in dnf | zypper) echo iproute ;; *) echo iproute2 ;; esac ;;
	conntrack) case "$1" in apt) echo conntrack ;; *) echo conntrack-tools ;; esac ;;
	semanage) echo policycoreutils-python-utils ;;
	esac
}

# pkg_install PM PKG...: install packages non-interactively. The first
# apt install refreshes the package lists: a fresh image (a cloud or SD
# card image) ships with none, and then nothing is installable.
APT_REFRESHED=""
pkg_install() {
	local pm="$1"; shift
	case "$pm" in
	apt)
		if [ -z "$APT_REFRESHED" ]; then
			APT_REFRESHED=1
			apt-get update -qq || true
		fi
		DEBIAN_FRONTEND=noninteractive apt-get install -y "$@" ;;
	dnf) dnf install -y "$@" ;;
	zypper) zypper --non-interactive install "$@" ;;
	# pacman: no -Sy here — syncing without upgrading is a partial
	# upgrade, which Arch warns can break the system; a fresh image whose
	# database is empty gets the -Syu hint on failure instead
	pacman) pacman -S --noconfirm --needed "$@" ;;
	apk) apk add --update-cache "$@" ;;
	esac
}

# valid_ipv4 ADDR: four decimal octets, each 0-255.
valid_ipv4() {
	local IFS=. o n=0
	echo "$1" | grep -Eq '^([0-9]{1,3}\.){3}[0-9]{1,3}$' || return 1
	for o in $1; do
		[ "$o" -le 255 ] || return 1
		n=$((n + 1))
	done
	[ "$n" = 4 ]
}

# gate_inverter_ip [FILE]: the inverter address in gate.env (its last
# INVERTER_IP line); empty when there is none yet (--no-inverter) or no
# file. Never fails.
gate_inverter_ip() {
	{ sed -n 's/^INVERTER_IP=//p' "${1:-/etc/foxess-local/gate.env}" 2>/dev/null || true; } | tail -1
}

# version_older A B: A and B are release tags (vX.Y.Z) and A is the older.
# A source build's version (a git hash) is never older: nothing to compare.
version_older() {
	local a b i
	[[ "$1" =~ ^v([0-9]+)\.([0-9]+)\.([0-9]+)$ ]] || return 1
	a=("${BASH_REMATCH[@]:1}")
	[[ "$2" =~ ^v([0-9]+)\.([0-9]+)\.([0-9]+)$ ]] || return 1
	b=("${BASH_REMATCH[@]:1}")
	for i in 0 1 2; do
		[ "$((10#${a[i]}))" -lt "$((10#${b[i]}))" ] && return 0
		[ "$((10#${a[i]}))" -gt "$((10#${b[i]}))" ] && return 1
	done
	return 1
}

# selinux_on: SELinux is enabled (enforcing or permissive).
selinux_on() { [ -f /sys/fs/selinux/enforce ]; }

# label_bin DIR: let the service exec the binaries in DIR under SELinux
# (Fedora and friends): var_lib_t is not executable by a service, bin_t
# is. semanage makes it a persistent rule; without it, chcon sets the
# type directly — files created there later (the app's own updates)
# inherit it, but a full filesystem relabel would reset it.
label_bin() {
	if command -v semanage >/dev/null 2>&1; then
		semanage fcontext -a -t bin_t "$1(/.*)?" 2>/dev/null || true
		restorecon -R "$1"
	else
		chcon -R -t bin_t "$1"
	fi
}

# yes_to QUESTION: --fix says yes; a terminal asks (default no);
# otherwise no (install review I5: nothing changes without consent).
yes_to() {
	[ -n "$FIX" ] && return 0
	[ -t 0 ] || return 1
	local a
	read -r -p "$1 [y/N] " a
	case "$a" in y | Y | yes | YES) return 0 ;; esac
	return 1
}

# why_tool TOOL: what a gate tool is for, and whether it is required —
# the question the offer asks must say why (and what "no" means).
why_tool() {
	case "$1" in
	nft) echo "REQUIRED: the gate's firewall rules are nftables; without it the install stops" ;;
	ip) echo "REQUIRED: the gate routes the inverter's cloud connection with it; without it the install stops" ;;
	semanage) echo "RECOMMENDED: SELinux is on here; it labels the app's directory so the service may run the binary, permanently (without it the label is set directly, and a full relabel of the filesystem would undo it)" ;;
	conntrack) echo "OPTIONAL: lets the 5-minute gate check also spot an inverter connection that got past the rules; without it that one scan is skipped and everything else works" ;;
	esac
}

# offer_fixes: missing gate tools (through the package manager) and IPv4
# forwarding (a sysctl.d drop-in), one yes/no each, saying why.
offer_fixes() {
	[ "$(id -u)" = 0 ] || return 0
	local pm tool pkg tools=""
	[ -z "$GATE" ] || tools="nft ip conntrack"
	[ -z "$APP" ] || ! selinux_on || tools="$tools semanage"
	pm=$(pkg_manager)
	for tool in $tools; do
		command -v "$tool" >/dev/null 2>&1 && continue
		pkg=$(pkg_for "${pm:-apt}" "$tool")
		echo
		echo "installer: '$tool' (package $pkg) is not installed."
		echo "  $(why_tool "$tool")"
		if [ -z "$pm" ]; then
			echo "  no known package manager here: install $pkg by hand"
		elif yes_to "  Install $pkg with $pm now?"; then
			if ! pkg_install "$pm" "$pkg"; then
				echo "  ! installing $pkg failed"
				[ "$pm" != pacman ] || echo "    (an empty package database? run: pacman -Syu, then this installer again)"
			fi
		else
			echo "  skipped (later: install the $pkg package, then re-run the installer)"
		fi
	done
	if [ "$(cat /proc/sys/net/ipv4/ip_forward 2>/dev/null)" != 1 ]; then
		echo
		echo "installer: IPv4 forwarding is off on this machine."
		echo "  RECOMMENDED: time sync (NTP) is the one inverter traffic the gate passes on to the"
		echo "  internet; without forwarding it cannot pass. The cloud connection, the app and the"
		echo "  web UI work either way. Yes writes /etc/sysctl.d/90-foxess.conf (net.ipv4.ip_forward=1)."
		if yes_to "  Turn on IPv4 forwarding now?"; then
			echo net.ipv4.ip_forward=1 > /etc/sysctl.d/90-foxess.conf && sysctl -q --system >/dev/null
		fi
	fi
}

if [ "$CMD" = check ]; then
	if check_requirements; then say "requirements met ($ARCH)"; exit 0; fi
	die "requirements not met"
fi
[ "$(id -u)" = 0 ] || die "must run as root"

# ---- uninstall ----
if [ "$CMD" = uninstall ]; then
	for u in foxess-local.service foxess-gate-check.timer foxess-gate.service foxess-gate-early.service; do
		systemctl disable --now "$u" 2>/dev/null || true
	done
	[ -x /usr/local/lib/foxess-local/apply-gate.sh ] && /usr/local/lib/foxess-local/apply-gate.sh down 2>/dev/null || true
	rm -f /etc/systemd/system/foxess-local.service /etc/systemd/system/foxess-gate.service /etc/systemd/system/foxess-gate-early.service \
		/etc/systemd/system/foxess-gate-check.service /etc/systemd/system/foxess-gate-check.timer
	rm -f /usr/local/lib/foxess-local/apply-gate.sh /usr/local/lib/foxess-local/check-gate.sh \
		/usr/local/lib/foxess-local/inventory-gate.sh /usr/local/lib/foxess-local/rollback.sh \
		/usr/local/lib/foxess-local/upgrade-guard.sh
	rmdir /usr/local/lib/foxess-local 2>/dev/null || true
	systemctl daemon-reload
	if command -v semanage >/dev/null 2>&1; then # the install's SELinux rules
		semanage fcontext -d '/usr/local/lib/foxess-local(/.*)?' 2>/dev/null || true
		[ -z "$PURGE" ] || semanage fcontext -d '/var/lib/foxess-local/bin(/.*)?' 2>/dev/null || true
	fi
	if [ -n "$PURGE" ]; then
		rm -rf /etc/foxess-local /var/lib/foxess-local /var/lib/foxess-gate
		# written by the IPv4-forwarding fix; the running setting is left
		# alone (forwarding stays on until the next boot)
		rm -f /etc/sysctl.d/90-foxess.conf
		userdel foxess 2>/dev/null || true
		say "removed, including config and data"
	else
		say "removed (kept /etc/foxess-local and /var/lib/foxess-local; --purge removes them)"
	fi
	say "set the inverter's network gateway back to your router: until then it still routes"
	say "through this machine, and with the gate gone it is neither filtered nor served"
	exit 0
fi

# ---- install ----
offer_fixes
echo "installer: checking requirements"
check_requirements || die "requirements not met (see above)"

if [ -n "$APP" ]; then
	if [ -z "$BIN" ]; then
		for c in "$SCRIPT_DIR/foxess-local_linux_$ARCH" "$SCRIPT_DIR/foxess-local"; do
			[ -f "$c" ] && { BIN="$c"; break; }
		done
	fi
	[ -n "$BIN" ] && [ -f "$BIN" ] || die "no binary: download foxess-local_linux_$ARCH next to this script, or pass --binary FILE"
	# never undo a self-upgrade silently (an older download re-run)
	NEW_VER="$("$BIN" version 2>/dev/null || true)"
	OLD_VER="$(/var/lib/foxess-local/bin/foxess-local version 2>/dev/null || true)"
	if [ -z "$DOWNGRADE" ] && version_older "$NEW_VER" "$OLD_VER"; then
		die "$BIN is $NEW_VER, older than the installed $OLD_VER (updated since?): use the newer release's files, or --allow-downgrade"
	fi
fi
if [ -n "$NO_INVERTER" ]; then
	[ -z "$INVERTER_IP" ] || die "--no-inverter and --inverter-ip: give one or the other"
	[ -n "$GATE" ] || die "--no-inverter is about the gate: not with --app-only"
	[ -z "$(gate_inverter_ip)" ] || die "--no-inverter: the inverter address is already set ($(gate_inverter_ip)); change it with --inverter-ip, or uninstall first"
fi
if [ -n "$GATE" ] && [ ! -f /etc/foxess-local/gate.env ]; then
	[ -n "$INVERTER_IP" ] || [ -n "$NO_INVERTER" ] || die "--inverter-ip is required on the first install (the inverter's LAN address; --no-inverter installs without one)"
fi
if [ -n "$INVERTER_IP" ]; then
	valid_ipv4 "$INVERTER_IP" || die "--inverter-ip: not an IPv4 address: $INVERTER_IP"
	for own in $(hostname -I 2>/dev/null); do
		[ "$own" != "$INVERTER_IP" ] || die "--inverter-ip: $INVERTER_IP is this machine's own address, not the inverter's"
	done
	if ip -4 route get "$INVERTER_IP" 2>/dev/null | grep -q ' via '; then
		say "warning: $INVERTER_IP is not on this machine's local network (it is reached through a router);"
		say "         the inverter must be on the same network for this machine to be its gateway"
	fi
fi
if [ -n "$INVERTER_MAC" ]; then
	echo "$INVERTER_MAC" | grep -Eq '^([0-9a-fA-F]{2}:){5}[0-9a-fA-F]{2}$' || die "--inverter-mac: not a MAC address: $INVERTER_MAC"
fi

# ---- what the vendor cloud may receive (first install: asked, never
# defaulted silently — install review I1) ----
if [ ! -f /etc/foxess-local/config.toml ]; then
	if [ -z "$FORWARD_MODE" ] && [ -t 0 ]; then
		echo
		echo "What may the inverter send to the FoxESS cloud?"
		echo "  off            nothing: the cloud and the FoxESS app see nothing (recommended to start)"
		echo "  telemetry_only readings only: the FoxESS app keeps showing data; the cloud cannot change anything"
		echo "  full           everything, as before: the cloud can change settings (firmware still needs a maintenance window)"
		echo "(You can change this at any time in the web UI: More -> Cloud.)"
		while :; do
			read -r -p "Choose off, telemetry_only or full: " FORWARD_MODE
			case "$FORWARD_MODE" in off | telemetry_only | full) break ;; esac
		done
	fi
	if [ -z "$FORWARD_MODE" ]; then
		FORWARD_MODE=off
		say "no --forward-mode given: the cloud receives nothing (off); change it in the web UI"
	fi
	case "$FORWARD_MODE" in off | telemetry_only | full) ;; *) die "--forward-mode: off, telemetry_only or full (not $FORWARD_MODE)" ;; esac
fi

# detect_mac IP: the inverter dongle's MAC from the neighbour table (it
# is there once the inverter has talked to this machine), or nothing.
# Never fails: on a first install the inverter is usually not pointed at
# this machine yet, and under pipefail a grep with no match would stop
# the install.
detect_mac() {
	# no address: `ip neigh show ""` would list every neighbour
	[ -n "$1" ] || return 0
	{ ip neigh show "$1" 2>/dev/null || true; } | { grep -oE 'lladdr ([0-9a-f]{2}:){5}[0-9a-f]{2}' || true; } | head -1 | cut -d' ' -f2
}

# write_file <dest> <mode> <owner:group or -> — content on stdin.
# Atomic: stage to <dest>.tmp.$$ in the destination directory, then
# rename — an interrupted install must not leave a truncated file.
write_file() {
	local dest="$1" mode="$2" owner="${3:--}"
	local tmp="${dest}.tmp.$$"
	cat > "$tmp"
	chmod "$mode" "$tmp"
	[ "$owner" = "-" ] || chown "$owner" "$tmp"
	mv -f "$tmp" "$dest"
}

if ! getent passwd foxess >/dev/null; then
	useradd --system --home /var/lib/foxess-local --shell /usr/sbin/nologin foxess
fi
install -d /usr/local/lib/foxess-local /etc/foxess-local /var/lib/foxess-gate
install -d -m 0700 -o foxess -g foxess /var/lib/foxess-local /var/lib/foxess-local/certs
install -d -m 0755 -o foxess -g foxess /var/lib/foxess-local/bin
PREAMBLE

# shellcheck disable=SC2016 # written literally into the installer
echo 'if [ -n "$GATE" ]; then'
emit deploy/apply-gate.sh      /usr/local/lib/foxess-local/apply-gate.sh      0755 root
emit deploy/check-gate.sh      /usr/local/lib/foxess-local/check-gate.sh      0755 root
emit deploy/inventory-gate.sh  /usr/local/lib/foxess-local/inventory-gate.sh  0755 root
emit deploy/rollback.sh        /usr/local/lib/foxess-local/rollback.sh        0755 root
emit deploy/gate.nft           /etc/foxess-local/gate.nft                     0644 root
emit deploy/foxess-gate.service       /etc/systemd/system/foxess-gate.service       0644 root
emit deploy/foxess-gate-early.service /etc/systemd/system/foxess-gate-early.service 0644 root
emit deploy/foxess-gate-check.service /etc/systemd/system/foxess-gate-check.service 0644 root
emit deploy/foxess-gate-check.timer   /etc/systemd/system/foxess-gate-check.timer   0644 root
cat <<'GATEENV'
	if [ -f /etc/foxess-local/gate.env ]; then
		say "keeping the existing /etc/foxess-local/gate.env"
		if [ -n "$INVERTER_IP" ] && ! grep -q "^INVERTER_IP=$INVERTER_IP\$" /etc/foxess-local/gate.env; then
			sed -i "s/^INVERTER_IP=.*/INVERTER_IP=$INVERTER_IP/" /etc/foxess-local/gate.env
			say "gate.env: INVERTER_IP updated to $INVERTER_IP"
		fi
		# the dongle's MAC (audit S2): given, or detected once and kept
		if [ -z "$INVERTER_MAC" ] && ! grep -q '^INVERTER_MAC=.' /etc/foxess-local/gate.env; then
			INVERTER_MAC="$(detect_mac "$(gate_inverter_ip)")"
		fi
		if [ -n "$INVERTER_MAC" ] && ! grep -q "^INVERTER_MAC=$INVERTER_MAC\$" /etc/foxess-local/gate.env; then
			sed -i '/^INVERTER_MAC=/d' /etc/foxess-local/gate.env
			echo "INVERTER_MAC=$INVERTER_MAC" >> /etc/foxess-local/gate.env
