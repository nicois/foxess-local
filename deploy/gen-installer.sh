FAILED=""
check() { # check LABEL HARD COMMAND...
	local label="$1" hard="$2"
	shift 2
	if "$@" >/dev/null 2>&1; then
		echo "  [ok]   $label"
	elif [ "$hard" = hard ]; then
		echo "  [FAIL] $label"
		FAILED=1
	else
		echo "  [--]   $label"
	fi
}
ui_ok() { # GET /healthz on the local listener (no curl needed)
	local reply
	# the group scopes 2>/dev/null to the connect (on a bare exec it would
	# silence the installer for good); not up yet: the caller retries
	{ exec 3<>/dev/tcp/127.0.0.1/18080; } 2>/dev/null || return 1
	printf 'GET /healthz HTTP/1.0\r\nHost: 127.0.0.1\r\n\r\n' >&3
	reply="$(timeout 5 cat <&3)"
	exec 3<&-
	echo "$reply" | grep -q '"status":"ok"'
}
